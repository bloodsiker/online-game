    private function article(
        LibraryCategory $category,
        string $title,
        string $slug,
        string $excerpt,
        string $content,
        int $sortOrder,
    ): void {
        LibraryArticle::withTrashed()->updateOrCreate(
            ['slug' => $slug],
            [
                'category_id' => $category->id,
                'author_id' => null,
                'title' => $title,
                'excerpt' => $excerpt,
                'content' => $content,
                'status' => LibraryArticle::STATUS_PUBLISHED,
                'published_at' => now(),
                'sort_order' => $sortOrder,
                'deleted_at' => null,
            ],
        );
    }


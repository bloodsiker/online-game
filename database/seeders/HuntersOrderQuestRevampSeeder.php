/**
 * Переработка квестов «Ордена Охотников» под актуальные карты и монстров.
 *
 * - 7 тиров × 5 квестов (старые квесты 95–115 переписываются на месте, недостающие создаются);
 * - подвиг только у тира 5000+ (см. HuntersOrderLegendFeatSeeder), у младших тиров подвиги сняты и отключены;
 * - «убить» — 100–200 монстров, «добыть» — количество/шанс ≈ 100–150 убийств.
 *
 * Старые квесты ищутся по прежнему русскому названию, новые — по новому, так что сидер
 * идемпотентен. Цели квестов пересоздаются; у игроков с квестом «в процессе» прогресс
 * по новым целям начинается с нуля.
 */
class HuntersOrderQuestRevampSeeder extends Seeder
{
    private const REPUTATION_ID = 2;

    private const NPC_ID = 4;

    public function run(): void
    {
        DB::transaction(function (): void {
            $items = $this->createTrophies();

            foreach ($this->tierQuests() as $minPoints => $quests) {
                $tierId = (int) DB::table('reputation_tiers')
                    ->where('reputation_id', self::REPUTATION_ID)
                    ->where('min_points', $minPoints)
                    ->value('id');

                foreach ($quests as $qd) {
                    $questId = $this->upsertQuest($qd, $items);
                    DB::table('reputation_tier_quests')->updateOrInsert(
                        ['tier_id' => $tierId, 'quest_id' => $questId],
                        ['created_at' => now(), 'updated_at' => now()],
                    );
                }
            }

            $this->removeLowerTierFeats();
        });

        // Подвиг тира 5000+ — многоэтапная цепочка «Тень Прародителя».
        $this->call(HuntersOrderLegendFeatSeeder::class);

        // Эликсиры лавки Ордена (нужен feat_quest_id подвига).
        $this->call(HuntersOrderElixirsSeeder::class);
    }

    /** Подвиг остаётся только у тира 5000+: у младших тиров он снимается, старые квесты-подвиги отключаются. */
    private function removeLowerTierFeats(): void
    {
        $featQuestIds = DB::table('reputation_tiers')
            ->where('reputation_id', self::REPUTATION_ID)
            ->where('min_points', '<', 5000)
            ->whereNotNull('feat_quest_id')
            ->pluck('feat_quest_id');

        DB::table('reputation_tiers')
            ->where('reputation_id', self::REPUTATION_ID)
            ->where('min_points', '<', 5000)
            ->update(['feat_quest_id' => null, 'feat_description_legacy' => null, 'feat_description' => null, 'updated_at' => now()]);

        DB::table('quests')->whereIn('id', $featQuestIds)->update(['is_active' => 0, 'updated_at' => now()]);
    }

    /**
     * @param  array<string, mixed>  $qd
     * @param  array<string, int>  $items
     */
    private function upsertQuest(array $qd, array $items, ?int $afterQuestId = null): int
    {
        $questId = null;
        foreach (array_filter([$qd['old'] ?? null, $qd['title'][0]]) as $title) {
            $questId = DB::table('quests')->where('title->ru', '[Орден] '.$title)->value('id');
            if ($questId !== null) {
                break;
            }
        }

        $row = [
            'title_legacy' => '[Орден] '.$qd['title'][0],
            'title' => $this->json(['[Орден] '.$qd['title'][0], '[Орден] '.$qd['title'][1]]),
            'description_legacy' => $qd['desc'][0],
            'description' => $this->json($qd['desc']),
            'type' => 'reputation',
            'start_npc_id' => self::NPC_ID,
            'complete_npc_id' => self::NPC_ID,
            'after_quest_id' => $afterQuestId,
            'is_active' => 1,
            'updated_at' => now(),
        ];

        if ($questId === null) {
            $questId = (int) DB::table('quests')->insertGetId($row + ['created_at' => now()]);
        } else {
            $questId = (int) $questId;
            DB::table('quests')->where('id', $questId)->update($row);
        }

        DB::table('quest_objectives')->where('quest_id', $questId)->delete();
        $objectiveIds = [];
        foreach ($qd['objs'] as [$type, $monsterIds, $amount, $desc, $item, $chance]) {
            $objectiveIds[] = (int) DB::table('quest_objectives')->insertGetId([
                'quest_id' => $questId,
                'type' => $type,
                'target_type' => 'monster',
                'target_id' => $monsterIds[0],
                'target_ids' => json_encode($monsterIds),
                'share_item_id' => $item !== null ? $items[$item] : null,
                'consume_item' => 1,
                'required_amount' => $amount,
                'drop_chance' => $chance,
                'description_legacy' => $desc[0],
                'description' => $this->json($desc),
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }

        // Активные квесты игроков получают новые цели с нулевым прогрессом.
        $activeQuestPlayerIds = DB::table('quest_players')
            ->where('quest_id', $questId)
            ->where('status', 'in_progress')
            ->pluck('id');
        foreach ($activeQuestPlayerIds as $questPlayerId) {
            foreach ($objectiveIds as $objectiveId) {
                DB::table('quest_player_objectives')->insert([
                    'quest_player_id' => $questPlayerId,
                    'quest_objective_id' => $objectiveId,
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
            }
        }

        DB::table('quest_rewards')->where('quest_id', $questId)->delete();
        [$rep, $exp, $money] = $qd['rewards'];
        DB::table('quest_rewards')->insert([
            ['quest_id' => $questId, 'type' => 'reputation_points', 'amount' => $rep, 'reputation_id' => self::REPUTATION_ID, 'created_at' => now(), 'updated_at' => now()],
            ['quest_id' => $questId, 'type' => 'exp', 'amount' => $exp, 'reputation_id' => null, 'created_at' => now(), 'updated_at' => now()],
            ['quest_id' => $questId, 'type' => 'money', 'amount' => $money, 'reputation_id' => null, 'created_at' => now(), 'updated_at' => now()],
        ]);

        return $questId;
    }

    /** @return array<string, int> ключ трофея → share_items.id */
    private function createTrophies(): array
    {
        $ids = [];
        foreach (self::TROPHIES as $key => [$ru, $uk, $descRu, $descUk]) {
            $id = DB::table('share_items')->where('type', 'quest')->where('name->ru', $ru)->value('id');
            $row = [
                'name_legacy' => $ru,
                'name' => $this->json([$ru, $uk]),
                'description_legacy' => $descRu,
                'description' => $this->json([$descRu, $descUk]),
                'updated_at' => now(),
            ];

            if ($id === null) {
                $id = DB::table('share_items')->insertGetId($row + [
                    'type' => 'quest',
                    'image' => null,
                    'is_active' => 1,
                    'is_sell' => 0,
                    'is_auction_sellable' => 0,
                    'is_give' => 1,
                    'is_droppable' => 1,
                    'is_stackable' => 1,
                    'is_use' => 0,
                    'is_weight' => 1,
                    'price' => 1,
                    'rarity' => 'common',
                    'created_at' => now(),
                ]);
            } else {
                DB::table('share_items')->where('id', $id)->update($row);
            }

            $ids[$key] = (int) $id;
        }

        return $ids;
    }

    /** @param  array{0: string, 1: string}  $pair */
    private function json(array $pair): string
    {
        return json_encode(['ru' => $pair[0], 'uk' => $pair[1]], JSON_UNESCAPED_UNICODE);
    }


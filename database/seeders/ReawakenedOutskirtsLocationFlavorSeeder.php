    private const QUIET_PATH_IDS_RANGE = [220, 244];

    private const GRAVES_IDS = [387, 388, 389, 390, 391, 392, 393, 394, 395];

    public function run(): void
    {
        $quietPathIds = DB::table('locations')
            ->where('map_id', 4)
            ->whereBetween('id', self::QUIET_PATH_IDS_RANGE)
            ->orderBy('id')
            ->pluck('id')
            ->values();

        $updated = $this->applyPool($quietPathIds, self::QUIET_PATH_POOL);
        $updated += $this->applyPool(collect(self::GRAVES_IDS), self::GRAVES_POOL);

        $this->command?->info("ReawakenedOutskirtsLocationFlavorSeeder: обновлено локаций — {$updated}");
    }

    /**
     * @param  \Illuminate\Support\Collection<int, int>  $locationIds
     * @param  array<int, array{name: string, description: string}>  $pool
     */
    private function applyPool(\Illuminate\Support\Collection $locationIds, array $pool): int
    {
        $poolSize = count($pool);
        $updated = 0;

        foreach ($locationIds as $index => $locationId) {
            $entry = $pool[$index % $poolSize];

            DB::table('locations')->where('id', $locationId)->update([
                'name' => $entry['name'],
                'description' => $entry['description'],
                'updated_at' => now(),
            ]);
            $updated++;
        }

        return $updated;
    }

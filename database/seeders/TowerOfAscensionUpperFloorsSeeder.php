    public function run(): void
    {
        foreach (self::FLOORS as $floor) {
            $existingStage = DB::table('dungeon_stages')
                ->where('dungeon_id', self::DUNGEON_ID)
                ->where('number', $floor['number'])
                ->first();

            if ($existingStage !== null) {
                $this->command?->info("Этаж {$floor['number']} уже существует (stage id={$existingStage->id}), пропускаю");

                continue;
            }

            $monsterId = LocalizedContentSeederQuery::forTable('monsters')->insertGetId([
                'name' => $floor['name'],
                'description' => $floor['description'],
                'lvl' => $floor['lvl'],
                'hp' => $floor['hp'],
                'armor' => $floor['armor'],
                'dodge' => $floor['dodge'],
                'critical' => $floor['critical'],
                'min_dmg' => $floor['minDmg'],
                'max_dmg' => $floor['maxDmg'],
                'attack_type' => 'physical',
                'magic_attack' => 0,
                'magic_power_coefficient' => 0,
                'magic_resistance' => 0,
                'aggression' => 0,
                'exp' => $floor['exp'],
                'min_money' => 0,
                'max_money' => 0,
                'is_boss' => 1,
                'does_not_regenerate_hp' => 1,
                'created_at' => now(),
                'updated_at' => now(),
            ]);

            $stageId = LocalizedContentSeederQuery::forTable('dungeon_stages')->insertGetId([
                'dungeon_id' => self::DUNGEON_ID,
                'number' => $floor['number'],
                'name' => $floor['name'],
                'completion_type' => 'kill_all',
                'spawn_type' => 'fixed',
                'total_monsters' => 1,
                'gold_budget' => $floor['goldBudget'],
                'created_at' => now(),
                'updated_at' => now(),
            ]);

            DB::table('dungeon_stage_monsters')->insert([
                'dungeon_stage_id' => $stageId,
                'monster_id' => $monsterId,
                'quantity' => 1,
                'weight' => 1,
                'created_at' => now(),
                'updated_at' => now(),
            ]);

            $this->command?->info(sprintf(
                'Этаж %d «%s» создан: monster id=%d (lvl%d, hp=%d), stage id=%d, gold_budget=%d',
                $floor['number'], $floor['name']['ru'], $monsterId, $floor['lvl'], $floor['hp'], $stageId, $floor['goldBudget'],
            ));
        }
    }

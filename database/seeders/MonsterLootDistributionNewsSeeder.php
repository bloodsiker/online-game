<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Modules\News\Infrastructure\Persistence\Models\NewsPost;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

final class MonsterLootDistributionNewsSeeder extends Seeder
{
    public function run(): void
    {
        DB::transaction(function (): void {
            $title = [
                'ru' => 'Добыча по заслугам: новое распределение лута и монет',
                'uk' => 'Здобич за заслугами: новий розподіл трофеїв і монет',
            ];
            if (NewsPost::where('title->ru', $title['ru'])->exists()) {
                return;
            }

            $news = new NewsPost([
                'title' => $title,
                'description' => [
                    'ru' => <<<'HTML'
<p>В мире <b>«Вечность»</b> обновлены правила распределения боевой добычи. Теперь право на трофеи определяет <b>вклад в победу над каждым монстром</b>, а не последний удар в бою.</p>
<h3>Больше урона — ваша добыча</h3>
<p><b>Монеты и право на предметный дроп получает игрок, нанёсший больше всего урона конкретному монстру.</b> Если в бою несколько противников, получатель определяется отдельно для каждого из них. Добивание последнего монстра больше не даёт права на всю добычу боя.</p>
<p>Учитываются обычные и магические удары, периодический урон и отражение. В зачёт идёт только <b>фактически снятое здоровье</b>: удар на 500 по монстру с остатком 10 здоровья добавит 10 урона. При равном результате добыча достаётся тому, кто раньше достиг этой суммы.</p>
<h3>Минута на подбор</h3>
<p>Предметная добыча появляется после завершения боя. Если она выпала на землю, <b>первую минуту её может подобрать только получатель</b>. Через 60 секунд предметы становятся доступны всем.</p>
<p><b>Предметы, выброшенные из рюкзака, не закрепляются за игроком</b> — их можно подобрать сразу.</p>
<h3>Премиум и совместные бои</h3>
<p>При доступном и включённом премиум-автолуте добыча отправляется прямо в рюкзак получателя, а в чат приходит личное сообщение. <b>Премиум другого участника не перехватывает ваши трофеи.</b></p>
<p>В группе действует то же правило: вклад каждого участника считается отдельно, минутная защита действует и для товарищей по группе. Награды клановых боссов по-прежнему распределяются по отдельным правилам кланового похода.</p>
HTML,
                    'uk' => <<<'HTML'
<p>У світі <b>«Вечность»</b> оновлено правила розподілу бойової здобичі. Тепер право на трофеї визначає <b>внесок у перемогу над кожним монстром</b>, а не останній удар у бою.</p>
<h3>Більше шкоди — ваша здобич</h3>
<p><b>Монети та право на предметні трофеї отримує гравець, який завдав найбільше шкоди конкретному монстру.</b> Якщо в бою кілька супротивників, одержувач визначається окремо для кожного з них. Добивання останнього монстра більше не дає права на всю здобич бою.</p>
<p>Враховуються звичайні та магічні удари, періодична шкода й відбиття. У залік іде лише <b>фактично зняте здоров’я</b>: удар на 500 по монстру із залишком 10 здоров’я додасть 10 шкоди. За однакового результату здобич отримує той, хто раніше досяг цієї суми.</p>
<h3>Хвилина на підбирання</h3>
<p>Предметні трофеї з’являються після завершення бою. Якщо вони випали на землю, <b>першу хвилину їх може підібрати лише одержувач</b>. Через 60 секунд предмети стають доступними всім.</p>
<p><b>Предмети, викинуті з рюкзака, не закріплюються за гравцем</b> — їх можна підібрати одразу.</p>
<h3>Преміум і спільні бої</h3>
<p>За доступного та ввімкненого преміум-автолуту здобич надходить просто до рюкзака одержувача, а в чат приходить особисте повідомлення. <b>Преміум іншого учасника не перехоплює ваші трофеї.</b></p>
<p>У групі діє те саме правило: внесок кожного учасника рахується окремо, хвилинний захист діє і для товаришів із групи. Нагороди кланових босів, як і раніше, розподіляються за окремими правилами кланового походу.</p>
HTML,
                ],
                'is_active' => true,
                'allow_comments' => true,
                'views_count' => 0,
            ]);
            foreach (['title', 'description'] as $field) {
                if (Schema::hasColumn('news_posts', $field.'_legacy')) {
                    $news->setAttribute($field.'_legacy', $news->getTranslation($field, 'ru'));
                }
            }
            $news->save();
            $this->command?->info('Новость опубликована: #'.$news->id.' — '.$title['ru']);
        });
    }
}

<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Modules\News\Infrastructure\Persistence\Models\NewsPost;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

final class TreasureHunterNewsSeeder extends Seeder
{
    public function run(): void
    {
        DB::transaction(function (): void {
            $title = [
                'ru' => 'По следам сокровищ: новая репутация «Кладоискатель»',
                'uk' => 'Слідами скарбів: нова репутація «Шукач скарбів»',
            ];
            if (NewsPost::where('title->ru', $title['ru'])->exists()) {
                return;
            }
            $description = [
                'ru' => <<<'HTML'
<p>Старые карты хранят немало тайн. В мире <b>«Вечность»</b> появилась новая репутация — <b>«Кладоискатель»</b>. Собирайте фрагменты карт, исследуйте территории и находите спрятанные сокровища!</p>
<h3>Четыре фрагмента — одна карта</h3>
<p>Для сборки нужны <b>четыре разных фрагмента I, II, III и IV одного тира</b>, по одному каждого вида. Нажмите на фрагмент в рюкзаке и выберите <b>«Собрать карту»</b>. Четыре одинаковых фрагмента или части разных тиров для сборки не подойдут.</p>
<p>У каждого экземпляра готовой карты случайно определяются <b>территория и место клада</b>. Название территории вы увидите сразу, а точную локацию предстоит найти самостоятельно. Повторная проверка карты не меняет место сокровища.</p>
<h3>Сверяйте карту с местностью</h3>
<p>Отправляйтесь на указанную территорию и используйте действие <b>«Сверить с местностью»</b> на карте в рюкзаке. Когда место совпадёт, карта активируется, а в её тултипе и информации о предмете появится номер локации. На странице локации станет доступна кнопка <b>«Искать клад»</b>.</p>
<p>Поиск занимает время и не всегда завершается удачей. Если тайник не обнаружен, карта сохраняется — можно повторить попытку. Одновременно можно искать сокровище по одной активированной карте.</p>
<h3>Находки и репутация</h3>
<p>При успешном поиске вы получите <b>закрытую шкатулку сокровищ в рюкзак и очки репутации</b>. Карта расходуется именно при обнаружении тайника. Чтобы добраться до содержимого шкатулки, потребуется взломать её замок подходящими отмычками. Не забывайте об условиях открытия и ловушках!</p>
<p>Повышайте репутацию: новые ступени открывают более сложные карты, <b>увеличивают шанс находки и сокращают время поиска</b>.</p>
<p>Проверить свои успехи можно в разделе <a href="/reputations?group=reputation"><b>«Репутации»</b></a>. Пусть следующая карта приведёт вас к удачной находке!</p>
HTML,
                'uk' => <<<'HTML'
<p>Старі карти зберігають чимало таємниць. У світі <b>«Вечность»</b> з’явилася нова репутація — <b>«Шукач скарбів»</b>. Збирайте фрагменти карт, досліджуйте території та знаходьте заховані скарби!</p>
<h3>Чотири фрагменти — одна карта</h3>
<p>Для збирання потрібні <b>чотири різні фрагменти I, II, III та IV одного рівня</b>, по одному кожного виду. Натисніть на фрагмент у рюкзаку та виберіть <b>«Зібрати карту»</b>. Чотири однакові фрагменти або частини різних рівнів для збирання не підійдуть.</p>
<p>Для кожного примірника готової карти випадково визначаються <b>територія та місце скарбу</b>. Назву території ви побачите одразу, а точну локацію доведеться знайти самостійно. Повторна перевірка карти не змінює місце скарбу.</p>
<h3>Звіряйте карту з місцевістю</h3>
<p>Вирушайте на зазначену територію та використовуйте дію <b>«Звірити з місцевістю»</b> на карті в рюкзаку. Коли місце збігатиметься, карта активується, а в її підказці та інформації про предмет з’явиться номер локації. На сторінці локації стане доступна кнопка <b>«Шукати скарб»</b>.</p>
<p>Пошук потребує часу й не завжди завершується вдало. Якщо схованку не виявлено, карта зберігається — можна повторити спробу. Одночасно можна шукати скарб за однією активованою картою.</p>
<h3>Знахідки та репутація</h3>
<p>За успішний пошук ви отримаєте <b>закриту скриньку скарбів до рюкзака та очки репутації</b>. Карта витрачається саме після виявлення схованки. Щоб дістатися до вмісту скриньки, потрібно зламати її замок відповідними відмичками. Не забувайте про умови відкриття та пастки!</p>
<p>Підвищуйте репутацію: нові щаблі відкривають складніші карти, <b>збільшують шанс знахідки та скорочують час пошуку</b>.</p>
<p>Перевірити свої успіхи можна в розділі <a href="/reputations?group=reputation"><b>«Репутації»</b></a>. Нехай наступна карта приведе вас до вдалої знахідки!</p>
HTML,
            ];
            $news = new NewsPost([
                'title' => $title, 'description' => $description,
                'is_active' => true, 'allow_comments' => true, 'views_count' => 0,
            ]);
            foreach (['title', 'description'] as $field) {
                if (Schema::hasColumn('news_posts', $field.'_legacy')) {
                    $news->setAttribute($field.'_legacy', $news->getTranslation($field, 'ru'));
                }
            }
            $news->save();
            $this->command?->info('Новость опубликована: #'.$news->id.' — '.$title['ru']);
        });
    }
}

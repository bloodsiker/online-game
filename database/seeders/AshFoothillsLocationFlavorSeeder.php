    public function run(): void
    {
        $locationIds = DB::table('locations')
            ->where('map_id', self::MAP_ID)
            ->whereNotIn('id', self::EXCLUDE_IDS)
            ->orderBy('id')
            ->pluck('id')
            ->values();

        $poolSize = count(self::POOL);
        $updated = 0;

        foreach ($locationIds as $index => $locationId) {
            $entry = self::POOL[$index % $poolSize];

            DB::table('locations')->where('id', $locationId)->update([
                'name' => $entry['name'],
                'description' => $entry['description'],
                'updated_at' => now(),
            ]);
            $updated++;
        }


    /**
     * @param  array{0: string, 1: string}  $name
     * @param  array{0: string, 1: string}  $desc
     * @param  array<string, mixed>  $columns
     */
    private function upsertMagicSkill(string $slug, array $name, array $desc, array $columns, int $requiredLevel): int
    {
        $row = $columns + [
            'name_legacy' => $name[0],
            'name' => $this->json($name),
            'description_legacy' => $desc[0],
            'description' => $this->json($desc),
            'min_damage' => 0,
            'max_damage' => 0,
            'power_coefficient' => 0,
            'base_healing' => 0,
            'updated_at' => now(),
        ];

        $id = DB::table('magic_skills')->where('slug', $slug)->value('id');
        if ($id === null) {
            $id = DB::table('magic_skills')->insertGetId($row + ['slug' => $slug, 'created_at' => now()]);
        } else {
            DB::table('magic_skills')->where('id', $id)->update($row);
        }

        DB::table('magic_skill_requirements')->where('magic_skill_id', $id)->delete();
        DB::table('magic_skill_requirements')->insert([
            'magic_skill_id' => $id, 'type' => 'level', 'min_value' => $requiredLevel, 'created_at' => now(), 'updated_at' => now(),
        ]);

        return (int) $id;
    }


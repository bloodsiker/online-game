    /**
     * @param  array<string, mixed>  $quest
     * @param  array<string, int>  $trophies
     */
    private function upsertQuest(array $quest, array $trophies, int $npcId): int
    {
        $questId = null;
        foreach (array_filter([$quest['old'] ?? null, $quest['title'][0]]) as $title) {
            $questId = DB::table('quests')->where('title->ru', self::PREFIX_RU.$title)->value('id');
            if ($questId !== null) {
                break;
            }
        }

        $row = [
            'title_legacy' => self::PREFIX_RU.$quest['title'][0],
            'title' => $this->json([self::PREFIX_RU.$quest['title'][0], self::PREFIX_UK.$quest['title'][1]]),
            'description_legacy' => $quest['desc'][0],
            'description' => $this->json($quest['desc']),
            'type' => 'reputation',
            'start_npc_id' => $npcId,
            'complete_npc_id' => $npcId,
            'is_active' => 1,
            'updated_at' => now(),
        ];

        if ($questId === null) {
            $questId = (int) DB::table('quests')->insertGetId($row + ['created_at' => now()]);
        } else {
            $questId = (int) $questId;
            DB::table('quests')->where('id', $questId)->update($row);
        }

        DB::table('quest_objectives')->where('quest_id', $questId)->delete();
        $objectiveIds = [];
        foreach ($quest['objs'] as [$type, $monsters, $amount, $desc, $trophy, $chance]) {
            $monsterIds = $this->monsterIds($monsters);
            $objectiveIds[] = (int) DB::table('quest_objectives')->insertGetId([
                'quest_id' => $questId,
                'type' => $type,
                'target_type' => 'monster',
                'target_id' => $monsterIds[0],
                'target_ids' => json_encode($monsterIds),
                'share_item_id' => $trophy !== null ? $trophies[$trophy] : null,
                'consume_item' => 1,
                'required_amount' => $amount,
                'drop_chance' => $chance,
                'description_legacy' => $desc[0],
                'description' => $this->json($desc),
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }

        // Активные квесты игроков получают новые цели с нулевым прогрессом.
        $activeQuestPlayerIds = DB::table('quest_players')
            ->where('quest_id', $questId)
            ->where('status', 'in_progress')
            ->pluck('id');
        foreach ($activeQuestPlayerIds as $questPlayerId) {
            foreach ($objectiveIds as $objectiveId) {
                DB::table('quest_player_objectives')->insert([
                    'quest_player_id' => $questPlayerId,
                    'quest_objective_id' => $objectiveId,
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
            }
        }

        DB::table('quest_rewards')->where('quest_id', $questId)->delete();
        [$rep, $exp, $money] = $quest['rewards'];
        DB::table('quest_rewards')->insert([
            ['quest_id' => $questId, 'type' => 'reputation_points', 'amount' => $rep, 'reputation_id' => self::REPUTATION_ID, 'created_at' => now(), 'updated_at' => now()],
            ['quest_id' => $questId, 'type' => 'exp', 'amount' => $exp, 'reputation_id' => null, 'created_at' => now(), 'updated_at' => now()],
            ['quest_id' => $questId, 'type' => 'money', 'amount' => $money, 'reputation_id' => null, 'created_at' => now(), 'updated_at' => now()],
        ]);

        return $questId;
    }

    /**
     * @param  list<array{0: string, 1: int}>  $monsters  [название, уровень]
     * @return list<int>
     */
    private function monsterIds(array $monsters): array
    {
        $ids = [];
        foreach ($monsters as [$name, $level]) {
            $id = DB::table('monsters')->where('name->ru', $name)->where('lvl', $level)->where('is_boss', 0)->value('id');
            if ($id === null) {
                throw new RuntimeException("Монстр «{$name}» {$level} ур. не найден");
            }
            $ids[] = (int) $id;
        }

        return $ids;
    }

    /** @return array<string, int> ключ трофея → share_items.id */
    private function upsertTrophies(): array
    {
        $ids = [];
        foreach (self::TROPHIES as $key => [$ru, $uk, $descRu, $descUk]) {
            $ids[$key] = $this->upsertItem('quest', [$ru, $uk], [
                $descRu.'<br><br>Трофей Городской стражи.',
                $descUk.'<br><br>Трофей Міської варти.',
            ], [
                'image' => null,
                'is_sell' => 0,
                'is_auction_sellable' => 0,
                'is_give' => 1,
                'is_droppable' => 1,
                'is_stackable' => 1,
                'is_use' => 0,
                'is_weight' => 1,
                'price' => 1,
                'rarity' => 'common',
            ]);
        }

        return $ids;
    }


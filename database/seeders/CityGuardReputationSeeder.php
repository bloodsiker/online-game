                    'share_structure_category_id' => $categoryId,
                    'price' => $price,
                    'diamond' => 0,
                    'min_reputation_points' => $minPoints,
                    'sort_order' => $sort,
                    'purchase_limit_quantity' => $line[5] ?? 0,
                    'purchase_limit_period_seconds' => $line[6] ?? 0,
                    'updated_at' => now(),
                    'created_at' => now(),
                ],
            );
            $keepIds[] = $shareItemId;
        }
        DB::table('shop_items')->where('structure_id', $shopId)->whereNotIn('share_item_id', $keepIds)->delete();
    }


    private function upsertShop(int $npcId): int
    {
        $nameRu = 'Интендантская стражи';
        $row = [
            'type' => 'shop',
            'name_legacy' => $nameRu,
            'name' => $this->json([$nameRu, 'Інтендантська варти']),
            'description_legacy' => '<p>Снаряжение и припасы для тех, кто служит Нейрину.</p>',
            'description' => $this->json(['<p>Снаряжение и припасы для тех, кто служит Нейрину.</p>', '<p>Спорядження та припаси для тих, хто служить Нейрину.</p>']),
            'location_id' => self::BARRACKS_LOCATION_ID,
            'npc_id' => $npcId,
            'reputation_id' => self::REPUTATION_ID,
            'updated_at' => now(),
        ];

        $id = DB::table('structures')->where('type', 'shop')->where('name->ru', $nameRu)->value('id');
        if ($id === null) {
            $row['image'] = DB::table('npcs')->where('id', $npcId)->value('image');
            $id = DB::table('structures')->insertGetId($row + ['created_at' => now()]);
        } else {
            DB::table('structures')->where('id', $id)->update($row);
        }

        foreach ([self::CATEGORY_ARMOR, self::CATEGORY_ELIXIRS, self::CATEGORY_BOOKS_SUPPORT, self::CATEGORY_BOOKS_PASSIVE, self::CATEGORY_MISC] as $categoryId) {
            DB::table('shop_categories')->updateOrInsert(['structure_id' => $id, 'share_structure_category_id' => $categoryId]);
        }

        return (int) $id;
    }


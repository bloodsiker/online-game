            $this->setLevelRequirement($id, $level);
            $lines[] = [$id, self::CATEGORY_ARMOR, $price, $minPoints, 10 + $i];
        }

        // Большие флаконы лечения: [ru, uk, мин. репутация, % HP, редкость, цена, образец]
        foreach (self::FLASKS as $i => [$ru, $uk, $minPoints, $percent, $rarity, $price, $templateId]) {

        foreach ($this->seedTeleportMechanisms() as $line) {
            $lines[] = $line;
        }

        // Гримуары: пассивка «Выносливость стража» и бафф «Бдительность дозорного».
        foreach ($this->seedBooks() as [$bookId, $category, $price, $minPoints, $sort]) {
            $lines[] = [$bookId, $category, $price, $minPoints, $sort];
        }

        $keepIds = [];
        foreach ($lines as $line) {
            [$shareItemId, $categoryId, $price, $minPoints, $sort] = $line;
            DB::table('shop_items')->updateOrInsert(
                ['structure_id' => $shopId, 'share_item_id' => $shareItemId],

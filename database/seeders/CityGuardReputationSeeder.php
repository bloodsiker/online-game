        $id = DB::table('effects')->where('slug', $slug)->value('id');
        if ($id === null) {
            return (int) DB::table('effects')->insertGetId($row + ['slug' => $slug, 'created_at' => now()]);
        }
        DB::table('effects')->where('id', $id)->update($row);

        return (int) $id;
    }

    /** @param  array{0: string, 1: string}  $skillName */
    private function upsertBook(int $skillId, array $skillName, string $kindRu, string $kindUk, ?string $image, string $rarity, int $price): int
    {
        $bookId = $this->upsertItem('book', ['Гримуар: «'.$skillName[0].'»', 'Гримуар: «'.$skillName[1].'»'], [
            "Учебник городской стражи. Прочитав его у Наставника магии, вы навсегда изучите {$kindRu} «{$skillName[0]}».",
            "Підручник міської варти. Прочитавши його в Наставника магії, ви назавжди вивчите {$kindUk} «{$skillName[1]}».",
        ], [
            'image' => $image,
            'rarity' => $rarity,
            'price' => $price,
            'is_stackable' => 1,
        ] + self::BOUND);

        DB::table('magic_skill_books')->updateOrInsert(
            ['share_item_id' => $bookId],
            ['magic_skill_id' => $skillId, 'updated_at' => now(), 'created_at' => now()],
        );

        return $bookId;
    }

    // ───────────────────────────── Хелперы ─────────────────────────────

    /**
     * @param  array{0: string, 1: string}  $name
     * @param  array{0: string, 1: string}  $desc
     * @param  array<string, mixed>  $columns
     */
    private function upsertItem(string $type, array $name, array $desc, array $columns): int
    {
        $row = $columns + [
            'name_legacy' => $name[0],
            'name' => $this->json($name),
            'description_legacy' => $desc[0],
            'description' => $this->json($desc),
            'updated_at' => now(),
        ];

        $id = DB::table('share_items')->where('type', $type)->where('name->ru', $name[0])->value('id');
        if ($id === null) {
            return (int) DB::table('share_items')->insertGetId($row + ['type' => $type, 'created_at' => now()]);
        }
        DB::table('share_items')->where('id', $id)->update($row);

        return (int) $id;
    }

    /** @param  array<string, int>  $stats */
    private function setStats(int $shareItemId, array $stats): void
    {
        DB::table('share_item_stats')->where('share_item_id', $shareItemId)->delete();
        foreach ($stats as $statType => $value) {
            DB::table('share_item_stats')->insert([
                'share_item_id' => $shareItemId, 'stat_type' => $statType, 'value' => $value, 'value_type' => 'flat',
                'created_at' => now(), 'updated_at' => now(),
            ]);
        }
    }

    private function setLevelRequirement(int $shareItemId, int $level): void
    {
        DB::table('share_item_requirements')->where('share_item_id', $shareItemId)->delete();
        DB::table('share_item_requirements')->insert([
            'share_item_id' => $shareItemId, 'type' => 'level', 'min_value' => $level, 'created_at' => now(), 'updated_at' => now(),
        ]);
    }

    private function setUseLimit(int $shareItemId, int $maxUses, int $periodSeconds): void
    {
        DB::table('share_item_use_limits')->updateOrInsert(
            ['share_item_id' => $shareItemId],
            ['max_uses' => $maxUses, 'period_seconds' => $periodSeconds, 'updated_at' => now(), 'created_at' => now()],
        );
    }

    /** @param  array{0: string, 1: string}  $pair */
    private function json(array $pair): string
    {
        return json_encode(['ru' => $pair[0], 'uk' => $pair[1]], JSON_UNESCAPED_UNICODE);
    }

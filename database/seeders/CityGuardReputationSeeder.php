                    ->where('min_points', $minPoints)
                    ->value('id');

                foreach ($quests as $quest) {
                    $questId = $this->upsertQuest($quest, $trophies, $npcId);
                    DB::table('reputation_tier_quests')->updateOrInsert(
                        ['tier_id' => $tierId, 'quest_id' => $questId],
                        ['created_at' => now(), 'updated_at' => now()],
                    );
                }
            }

            $shopId = $this->upsertShop($npcId);
            $this->seedShop($shopId);

            // Старая «лавка репутации» стражи (легендарные зелья за 500 монет) больше не используется.
            DB::table('reputation_shop_items')->where('reputation_id', self::REPUTATION_ID)->delete();
        });
    }


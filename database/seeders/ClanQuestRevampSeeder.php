    public function run(): void
    {
        $this->assertMonsters();

        DB::transaction(function (): void {
            foreach (self::QUESTS as $index => $quest) {
                $this->upsertQuest($quest, self::LEGACY_QUEST_IDS[$index] ?? null);
            }
        });
    }

    /** @param  array<string, mixed>  $qd */
    private function upsertQuest(array $qd, ?int $legacyId): void
    {
        $questId = $legacyId !== null && DB::table('quests')->where('id', $legacyId)->where('type', 'clan')->exists()
            ? $legacyId
            : DB::table('quests')->where('type', 'clan')->whereIn('title->ru', array_filter([$qd['title'][0], $qd['old'] ?? null]))->value('id');

        $row = [
            'title_legacy' => $qd['title'][0],
            'title' => $this->json($qd['title']),
            'description_legacy' => $qd['desc'][0],
            'description' => $this->json($qd['desc']),
            'type' => 'clan',
            'start_npc_id' => self::NPC_ID,
            'complete_npc_id' => self::NPC_ID,
            'reset_period' => $qd['period'],
            'is_active' => 1,
            'updated_at' => now(),
        ];

        if ($questId === null) {
            $questId = (int) DB::table('quests')->insertGetId($row + ['created_at' => now()]);
        } else {
            $questId = (int) $questId;
            DB::table('quests')->where('id', $questId)->update($row);
        }

        $oldObjectiveIds = DB::table('quest_objectives')->where('quest_id', $questId)->pluck('id');
        DB::table('quest_clan_objectives')->whereIn('quest_objective_id', $oldObjectiveIds)->delete();
        DB::table('quest_objectives')->whereIn('id', $oldObjectiveIds)->delete();

        $objectiveIds = [];
        foreach ($qd['objs'] as [$monsterName, $amount, $desc]) {
            $monsterIds = $this->monsterIds($monsterName);
            $objectiveIds[] = (int) DB::table('quest_objectives')->insertGetId([
                'quest_id' => $questId,
                'type' => 'kill',
                'target_type' => 'monster',
                'target_id' => $monsterIds[0],
                'target_ids' => json_encode($monsterIds),
                'consume_item' => 0,
                'required_amount' => $amount,
                'description_legacy' => $desc[0],
                'description' => $this->json($desc),
                'created_at' => now(),
                'updated_at' => now(),
            ]);
        }

        // Кланы с квестом «в процессе» получают новые цели с нулевым прогрессом.
        $activeProgressIds = DB::table('quest_clan_progress')
            ->where('quest_id', $questId)
            ->where('status', 'in_progress')
            ->pluck('id');
        foreach ($activeProgressIds as $progressId) {
            foreach ($objectiveIds as $objectiveId) {
                DB::table('quest_clan_objectives')->insert([
                    'quest_clan_progress_id' => $progressId,
                    'quest_objective_id' => $objectiveId,
                    'amount' => 0,
                    'created_at' => now(),
                    'updated_at' => now(),
                ]);
            }
        }

        DB::table('quest_rewards')->where('quest_id', $questId)->delete();
        DB::table('quest_rewards')->insert([
            ['quest_id' => $questId, 'type' => 'clan_points', 'amount' => $qd['points'], 'created_at' => now(), 'updated_at' => now()],
            ['quest_id' => $questId, 'type' => 'money', 'amount' => $qd['money'], 'created_at' => now(), 'updated_at' => now()],
        ]);
    }

    private function assertMonsters(): void
    {
        foreach (self::QUESTS as $quest) {
            foreach ($quest['objs'] as [$monsterName]) {
                $this->monsterIds($monsterName);
            }
        }
    }

    /**
     * Все уровни монстра с этим именем — в цели засчитывается любой из них.
     *
     * @return list<int>
     */
    private function monsterIds(string $name): array
    {
        $ids = DB::table('monsters')->where('name->ru', $name)->orderBy('lvl')->pluck('id')->map(fn ($id): int => (int) $id)->all();

        return $ids !== [] ? $ids : throw new RuntimeException("Нет монстра «{$name}»");
    }

    /** @param  array{0: string, 1: string}  $pair */
    private function json(array $pair): string
    {
        return json_encode(['ru' => $pair[0], 'uk' => $pair[1]], JSON_UNESCAPED_UNICODE);
    }

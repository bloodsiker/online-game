<?php

declare(strict_types=1);

namespace Database\Seeders;

use App\Modules\News\Infrastructure\Persistence\Models\NewsPost;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

final class TelegramMiniAppNewsSeeder extends Seeder
{
    public function run(): void
    {
        DB::transaction(function (): void {
            $title = [
                'ru' => '«Вечность app» — персонаж, рюкзак и чат в Telegram',
                'uk' => '«Вечность app» — персонаж, рюкзак і чат у Telegram',
            ];
            if (NewsPost::query()->where('title->ru', $title['ru'])->exists()) {
                $this->command?->info('Новость о Telegram App уже существует.');

                return;
            }

            $description = [
                'ru' => <<<'HTML'
<p><img src="/main/images/news/telegram.svg" width="56" height="56" alt="Telegram" style="float:left;margin:0 12px 8px 0">Теперь следить за персонажем и общаться с другими игроками можно прямо в Telegram. Встречайте <b>«Вечность app»</b> — мини-приложение игры с удобным интерфейсом для телефона!</p>
<h3>Что уже доступно?</h3>
<ul>
<li><b>Персонаж:</b> аватар, уровень, монеты и бриллианты, здоровье, мана, характеристики и боевые и мирные умения. Отдельные вкладки показывают ваши репутации и влияние.</li>
<li><b>Сумка:</b> предметы по категориям с картинками, количеством и уровнем заточки. Нажмите на предмет, чтобы посмотреть его описание.</li>
<li><b>Аукцион:</b> все активные лоты и ваши предложения. Ищите предметы по названию, типу и редкости. Пока здесь доступен просмотр: покупать и выставлять лоты нужно в самой игре.</li>
<li><b>Чат:</b> читайте сообщения и общайтесь с игроками, в том числе в личной переписке и доступных вам каналах.</li>
<li><b>Игроки онлайн:</b> общий счётчик и список персонажей со ссылками на их публичные профили.</li>
</ul>
<h3>Как подключиться?</h3>
<ol>
<li>Откройте в игре <a href="/settings"><b>настройки персонажа</b></a> и найдите блок <b>Telegram</b>.</li>
<li>Нажмите <b>«Привязать Telegram»</b> и перейдите в бота по своей ссылке из открывшегося окна.</li>
<li>После привязки нажмите в боте <b>«Вечность app»</b> и откройте мини-приложение.</li>
</ol>
<p>Интерфейс поддерживает <b>русский и украинский языки</b> и использует язык, выбранный в настройках игры. Теперь ваш персонаж и друзья ещё ближе!</p>
HTML,
                'uk' => <<<'HTML'
<p><img src="/main/images/news/telegram.svg" width="56" height="56" alt="Telegram" style="float:left;margin:0 12px 8px 0">Тепер стежити за персонажем і спілкуватися з іншими гравцями можна просто в Telegram. Зустрічайте <b>«Вечность app»</b> — мініпрограму гри зі зручним інтерфейсом для телефона!</p>
<h3>Що вже доступно?</h3>
<ul>
<li><b>Персонаж:</b> аватар, рівень, монети й діаманти, здоров’я, мана, характеристики та бойові й мирні вміння. Окремі вкладки показують ваші репутації та вплив.</li>
<li><b>Сумка:</b> предмети за категоріями із зображеннями, кількістю та рівнем заточування. Натисніть на предмет, щоб переглянути його опис.</li>
<li><b>Аукціон:</b> усі активні лоти та ваші пропозиції. Шукайте предмети за назвою, типом і рідкістю. Поки тут доступний перегляд: купувати та виставляти лоти потрібно в самій грі.</li>
<li><b>Чат:</b> читайте повідомлення та спілкуйтеся з гравцями, зокрема в особистому листуванні й доступних вам каналах.</li>
<li><b>Гравці онлайн:</b> загальний лічильник і список персонажів із посиланнями на їхні публічні профілі.</li>
</ul>
<h3>Як підключитися?</h3>
<ol>
<li>Відкрийте у грі <a href="/settings"><b>налаштування персонажа</b></a> та знайдіть блок <b>Telegram</b>.</li>
<li>Натисніть <b>«Прив’язати Telegram»</b> і перейдіть до бота за своїм посиланням із відкритого вікна.</li>
<li>Після прив’язки натисніть у боті <b>«Вечность app»</b> та відкрийте мініпрограму.</li>
</ol>
<p>Інтерфейс підтримує <b>російську та українську мови</b> й використовує мову, вибрану в налаштуваннях гри. Тепер ваш персонаж і друзі ще ближче!</p>
HTML,
            ];

            $botUsername = ltrim((string) config('telegram.bot_username'), '@');
            if (preg_match('/^[a-zA-Z0-9_]+$/D', $botUsername)) {
                $link = '<a href="https://t.me/'.e($botUsername).'" target="_blank" rel="noopener noreferrer"><b>@'.e($botUsername).'</b></a>';
                $description['ru'] .= '<p>Наш Telegram-бот: '.$link.'. Для доступа к своему персонажу сначала выполните привязку в настройках игры.</p>';
                $description['uk'] .= '<p>Наш Telegram-бот: '.$link.'. Для доступу до свого персонажа спочатку виконайте прив’язку в налаштуваннях гри.</p>';
            }

            $news = new NewsPost([
                'title' => $title, 'description' => $description,
                'is_active' => true, 'allow_comments' => true, 'views_count' => 0,
            ]);
            foreach (['title', 'description'] as $field) {
                if (Schema::hasColumn('news_posts', $field.'_legacy')) {
                    $news->setAttribute($field.'_legacy', $news->getTranslation($field, 'ru'));
                }
            }
            $news->save();
            $this->command?->info('Новость опубликована: #'.$news->id.' — '.$title['ru']);
        });
    }
}

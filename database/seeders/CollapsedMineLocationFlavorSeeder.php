    public function run(): void
    {
        $updated = 0;

        // Сама решётка — две уникальные локации по разные стороны порога,
        // без циклического пула (их всего две, см. location_gates id=11/12).
        DB::table('locations')->where('id', 1555)->update([
            'name' => 'Решётка Запертой Штольни',
            'description' => 'Массивная ржавая решётка, перекрывающая проход вглубь — её ставили явно не против обвала, а против чего-то, что могло выйти оттуда само.',
            'updated_at' => now(),
        ]);
        DB::table('locations')->where('id', 1556)->update([
            'name' => 'Проход За Решёткой',
            'description' => 'Участок сразу за решёткой — воздух здесь заметно тише и холоднее, будто выработка за порогом существует по своим собственным правилам.',
            'updated_at' => now(),
        ]);
        $updated += 2;

        $bands = [
            ['range' => [1531, 1554], 'pool' => self::OUTER],
            ['range' => [1557, 1581], 'pool' => self::INNER],
        ];

        foreach ($bands as $band) {
            [$fromId, $toId] = $band['range'];
            $pool = $band['pool'];
            $poolSize = count($pool);

            $locationIds = DB::table('locations')
                ->whereBetween('id', [$fromId, $toId])
                ->orderBy('id')
                ->pluck('id')
                ->values();

            foreach ($locationIds as $index => $locationId) {
                $entry = $pool[$index % $poolSize];

                DB::table('locations')->where('id', $locationId)->update([
                    'name' => $entry['name'],
                    'description' => $entry['description'],
                    'updated_at' => now(),
                ]);
                $updated++;
            }

            $this->command?->info(sprintf(
                '%d-%d: %d локаций переименовано (пул из %d названий)',
                $fromId, $toId, $locationIds->count(), $poolSize,
            ));
        }

        $this->command?->info("CollapsedMineLocationFlavorSeeder: обновлено локаций — {$updated}");
    }

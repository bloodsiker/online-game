    public function run(): void
    {
        $updated = 0;

        foreach (self::LOCATIONS as $locationId => $entry) {
            $affected = DB::table('locations')->where('id', $locationId)->update([
                'name' => $entry['name'],
                'description' => $entry['description'],
                'updated_at' => now(),
            ]);
            $updated += $affected;
        }

        $this->command?->info("CarrigmoreRoadLocationFlavorSeeder: обновлено локаций — {$updated}");
    }

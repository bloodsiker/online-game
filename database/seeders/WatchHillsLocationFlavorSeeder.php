    public function run(): void
    {
        $bands = [
            ['range' => [1117, 1164], 'pool' => self::BAND_1],
            ['range' => [1165, 1231], 'pool' => self::BAND_2],
            ['range' => [1232, 1278], 'pool' => self::BAND_3],
        ];

        $updated = 0;

        foreach ($bands as $band) {
            [$fromId, $toId] = $band['range'];
            $pool = $band['pool'];
            $poolSize = count($pool);

            $locationIds = DB::table('locations')
                ->whereBetween('id', [$fromId, $toId])
                ->orderBy('id')
                ->pluck('id')
                ->values();

            foreach ($locationIds as $index => $locationId) {
                $entry = $pool[$index % $poolSize];

                DB::table('locations')->where('id', $locationId)->update([
                    'name' => $entry['name'],
                    'description' => $entry['description'],
                    'updated_at' => now(),
                ]);
                $updated++;
            }

            $this->command?->info(sprintf(
                'полоса %d-%d: %d локаций переименовано (пул из %d названий)',
                $fromId, $toId, $locationIds->count(), $poolSize,
            ));
        }

        $this->command?->info("WatchHillsLocationFlavorSeeder: обновлено локаций — {$updated}");
    }

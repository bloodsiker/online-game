<?php

declare(strict_types=1);

namespace App\Modules\Weather\Domain\Enums;

/**
 * Погодные явления на картах. Параметры эффектов — константы WeatherRules.
 * Этап 1: гроза (Простуда), радуга (бафф после грозы), туман (шансы в бою).
 * Метель, ветер, ураган и зной — следующие этапы (перемещение и регенерация).
 */
enum WeatherType: string
{
    case STORM = 'storm';
    case RAINBOW = 'rainbow';
    case FOG = 'fog';
    case HEAT = 'heat';
    case BLIZZARD = 'blizzard';
    case TAILWIND = 'tailwind';
    case HURRICANE = 'hurricane';

    public function label(): string
    {
        return match ($this) {
            self::STORM => __('Гроза'),
            self::RAINBOW => __('Радуга'),
            self::FOG => __('Густой туман'),
            self::HEAT => __('Зной'),
            self::BLIZZARD => __('Метель'),
            self::TAILWIND => __('Попутный ветер'),
            self::HURRICANE => __('Ураган'),
        };
    }

    public function isGood(): bool
    {
        return in_array($this, [self::RAINBOW, self::TAILWIND], true);
    }

    public function description(): string
    {
        return match ($this) {
            self::STORM => __('Над округой гремит гроза, небо затянуто тучами, на землю льются холодные струи дождя.'),
            self::RAINBOW => __('Гроза отступила, и над землёй поднялась яркая радуга. Свежий воздух придаёт сил.'),
            self::FOG => __('Густой туман окутал округу — в двух шагах ничего не видно.'),
            self::HEAT => __('Палящее солнце выжигает всё вокруг, воздух дрожит от жары.'),
            self::BLIZZARD => __('Метель заметает тропы, идти приходится медленно.'),
            self::TAILWIND => __('Попутный ветер подгоняет путников в дороге.'),
            self::HURRICANE => __('Ураганный ветер сбивает с ног и уносит в сторону.'),
        };
    }

    public function effectText(): string
    {
        return match ($this) {
            self::STORM => __('Под ливнем легко простудиться: «Простуда» на время заметно ослабляет все характеристики.'),
            self::RAINBOW => __('Каждый, кто приходит сюда, получает «Радугу»: на время характеристики немного усиливаются.'),
            self::FOG => __('Пока вы в тумане, действует «Туман»: заметно снижены уворот и крит, а противникам легче уклоняться от ваших ударов.'),
            self::HEAT => __('Под палящим солнцем силы возвращаются с трудом: здоровье и мана восстанавливаются заметно медленнее.'),
            self::BLIZZARD => __('Метель заметает тропы: переходы между локациями занимают заметно больше времени.'),
            self::TAILWIND => __('Ветер дует в спину: переходы между локациями занимают заметно меньше времени.'),
            self::HURRICANE => __('Сильные порывы ветра иногда сбивают путников с пути и уносят на соседнюю локацию.'),
        };
    }
}

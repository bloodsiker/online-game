<h1>Лицензионное соглашение</h1>
<p class="eula__updated">Редакция от 18 ноября 2026 года</p>

<p>Настоящее Лицензионное соглашение (далее — «Соглашение») регулирует отношения между Администрацией онлайн-игры «Вечность» (Eternum) (далее — «Администрация») и пользователем сети Интернет (далее — «Игрок»), использующим игру, размещённую на сайте {{ parse_url(config('app.url'), PHP_URL_HOST) ?? request()->getHost() }} (далее — «Игра»).</p>
<p>Регистрируясь в Игре или начиная ею пользоваться, Игрок подтверждает, что прочитал Соглашение, понимает его и принимает все его условия в полном объёме. Если Игрок не согласен с каким-либо условием, он должен прекратить использование Игры.</p>

<h2>1. Термины</h2>
<ol>
    <li><b>Игра</b> — браузерная многопользовательская ролевая онлайн-игра «Вечность», включая её программный код, графику, тексты, звуки, игровой мир и все связанные сервисы (сайт, форум, чат).</li>
    <li><b>Аккаунт</b> — учётная запись Игрока, доступ к которой осуществляется по адресу электронной почты и паролю.</li>
    <li><b>Персонаж</b> — игровой образ Игрока, созданный в рамках Аккаунта.</li>
    <li><b>Игровые ценности</b> — предметы, игровая валюта, Eternum, опыт, репутация, умения и иные виртуальные объекты Игры.</li>
    <li><b>Дополнительные услуги</b> — платные возможности Игры, предоставляемые за Eternum или реальные деньги.</li>
</ol>

<h2>2. Предмет соглашения</h2>
<ol>
    <li>Администрация предоставляет Игроку простую (неисключительную), безвозмездную, отзывную лицензию на использование Игры в развлекательных целях на условиях Соглашения.</li>
    <li>Базовый доступ к Игре бесплатный. Дополнительные услуги не являются обязательными для прохождения Игры.</li>
    <li>Игра предоставляется «как есть». Администрация не гарантирует, что Игра будет соответствовать ожиданиям Игрока, работать бесперебойно и без ошибок.</li>
</ol>

<h2>3. Регистрация и Аккаунт</h2>
<ol>
    <li>При регистрации Игрок обязан указать действующий адрес электронной почты. Игроку разрешено иметь не более одного Аккаунта, если иное прямо не разрешено Администрацией.</li>
    <li>Игрок самостоятельно отвечает за сохранность пароля и за все действия, совершённые с его Аккаунта. Администрация никогда не запрашивает пароль Игрока.</li>
    <li>Запрещено продавать, покупать, передавать, сдавать в аренду Аккаунты и Персонажей, а также совместно использовать один Аккаунт несколькими лицами.</li>
    <li>Имя Персонажа не должно содержать нецензурных и оскорбительных слов, призывов к насилию, рекламы, имён представителей Администрации и названий, вводящих других Игроков в заблуждение. Администрация вправе принудительно сменить такое имя.</li>
    <li>Если Игрок не достиг возраста, с которого законодательство его страны позволяет самостоятельно заключать подобные соглашения, он может пользоваться Игрой только с согласия родителей или законных представителей.</li>
</ol>

<h2>4. Правила поведения</h2>
<p>Игроку запрещается:</p>
<ol>
    <li>использовать ботов, скрипты, макросы, кликеры и любые программы, автоматизирующие игровые действия или дающие преимущество над другими Игроками;</li>
    <li>использовать ошибки (баги) Игры в своих интересах и скрывать их от Администрации;</li>
    <li>вмешиваться в работу серверов, взламывать, декомпилировать или модифицировать программный код Игры, перехватывать и подделывать сетевые запросы;</li>
    <li>обменивать Игровые ценности на реальные деньги или иные ценности вне Игры, а также предлагать подобные услуги;</li>
    <li>оскорблять, угрожать, преследовать других Игроков и Администрацию, разжигать вражду по любому признаку;</li>
    <li>распространять спам, рекламу сторонних ресурсов, вредоносные ссылки;</li>
    <li>выдавать себя за представителя Администрации;</li>
    <li>обманывать других Игроков с целью завладеть их Аккаунтом или Игровыми ценностями;</li>
    <li>нарушать иные правила Игры, опубликованные на сайте и форуме.</li>
</ol>

<h2>5. Игровые ценности и Дополнительные услуги</h2>
<ol>
    <li>Все Игровые ценности являются частью Игры и принадлежат Администрации. Игрок получает лишь право пользоваться ими в Игре на время действия Соглашения. Игровые ценности не являются имуществом Игрока и не имеют денежной стоимости.</li>
    <li>Оплачивая Дополнительные услуги, Игрок приобретает право использовать соответствующие игровые возможности. Услуга считается оказанной в полном объёме в момент зачисления Eternum или активации возможности на Аккаунте.</li>
    <li>Средства, уплаченные за Дополнительные услуги, не возвращаются, в том числе при блокировке Аккаунта за нарушение Соглашения, добровольном прекращении игры или изменении игрового баланса. Исключение — ошибочное или повторное списание, подтверждённое Администрацией.</li>
    <li>Администрация вправе изменять характеристики, стоимость и способы получения Игровых ценностей, вводить и выводить из Игры предметы и возможности, проводить балансные изменения. Такие изменения не являются основанием для компенсации.</li>
    <li>Игровые ценности, утраченные по вине Игрока (передача пароля, обман со стороны других Игроков, ошибочные действия), не восстанавливаются. Ценности, утраченные из-за технического сбоя на стороне Игры, восстанавливаются на усмотрение Администрации при наличии подтверждения в журналах сервера.</li>
</ol>

<h2>6. Права Администрации</h2>
<ol>
    <li>Администрация вправе в любой момент изменять Игру, проводить технические работы, временно ограничивать доступ к Игре.</li>
    <li>За нарушение Соглашения или правил Игры Администрация вправе применить к Игроку меры воздействия: предупреждение, ограничение чата, изъятие полученных нечестным путём Игровых ценностей, временную или бессрочную блокировку Аккаунта, в том числе всех связанных Аккаунтов.</li>
    <li>Администрация не обязана объяснять Игроку причины применённых мер, если это может помочь в обходе защиты Игры.</li>
    <li>Администрация вправе удалять Аккаунты, в которые не входили более 12 месяцев и на которых не приобретались Дополнительные услуги.</li>
    <li>Администрация вправе отправлять Игроку на указанный адрес электронной почты служебные сообщения и новости Игры. От новостных рассылок можно отказаться.</li>
</ol>


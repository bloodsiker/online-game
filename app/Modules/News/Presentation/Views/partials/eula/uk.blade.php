<h1>Ліцензійна угода</h1>
<p class="eula__updated">Редакція від 18 листопада 2026 року</p>

<p>Ця Ліцензійна угода (далі — «Угода») регулює відносини між Адміністрацією онлайн-гри «Вічність» (Eternum) (далі — «Адміністрація») і користувачем мережі Інтернет (далі — «Гравець»), який користується грою, розміщеною на сайті {{ parse_url(config('app.url'), PHP_URL_HOST) ?? request()->getHost() }} (далі — «Гра»).</p>
<p>Реєструючись у Грі або починаючи нею користуватися, Гравець підтверджує, що прочитав Угоду, розуміє її та приймає всі її умови в повному обсязі. Якщо Гравець не згоден з якоюсь умовою, він має припинити користування Грою.</p>

<h2>1. Терміни</h2>
<ol>
    <li><b>Гра</b> — браузерна багатокористувацька рольова онлайн-гра «Вічність», включно з її програмним кодом, графікою, текстами, звуками, ігровим світом і всіма пов'язаними сервісами (сайт, форум, чат).</li>
    <li><b>Акаунт</b> — обліковий запис Гравця, доступ до якого здійснюється за адресою електронної пошти та паролем.</li>
    <li><b>Персонаж</b> — ігровий образ Гравця, створений у межах Акаунта.</li>
    <li><b>Ігрові цінності</b> — предмети, ігрова валюта, Eternum, досвід, репутація, уміння та інші віртуальні об'єкти Гри.</li>
    <li><b>Додаткові послуги</b> — платні можливості Гри, що надаються за Eternum або реальні гроші.</li>
</ol>

<h2>2. Предмет угоди</h2>
<ol>
    <li>Адміністрація надає Гравцеві просту (невиключну), безоплатну, відкличну ліцензію на використання Гри з розважальною метою на умовах Угоди.</li>
    <li>Базовий доступ до Гри безкоштовний. Додаткові послуги не є обов'язковими для проходження Гри.</li>
    <li>Гра надається «як є». Адміністрація не гарантує, що Гра відповідатиме очікуванням Гравця, працюватиме безперебійно та без помилок.</li>
</ol>

<h2>3. Реєстрація та Акаунт</h2>
<ol>
    <li>Під час реєстрації Гравець зобов'язаний вказати чинну адресу електронної пошти. Гравцеві дозволено мати не більше одного Акаунта, якщо інше прямо не дозволено Адміністрацією.</li>
    <li>Гравець самостійно відповідає за збереження пароля та за всі дії, вчинені з його Акаунта. Адміністрація ніколи не запитує пароль Гравця.</li>
    <li>Заборонено продавати, купувати, передавати, здавати в оренду Акаунти й Персонажів, а також спільно використовувати один Акаунт кількома особами.</li>
    <li>Ім'я Персонажа не повинно містити нецензурних та образливих слів, закликів до насильства, реклами, імен представників Адміністрації та назв, що вводять інших Гравців в оману. Адміністрація має право примусово змінити таке ім'я.</li>
    <li>Якщо Гравець не досяг віку, з якого законодавство його країни дозволяє самостійно укладати подібні угоди, він може користуватися Грою лише за згодою батьків або законних представників.</li>
</ol>

<h2>4. Правила поведінки</h2>
<p>Гравцеві забороняється:</p>
<ol>
    <li>використовувати ботів, скрипти, макроси, клікери та будь-які програми, що автоматизують ігрові дії або дають перевагу над іншими Гравцями;</li>
    <li>використовувати помилки (баги) Гри у своїх інтересах і приховувати їх від Адміністрації;</li>
    <li>втручатися в роботу серверів, зламувати, декомпілювати чи модифікувати програмний код Гри, перехоплювати й підробляти мережеві запити;</li>
    <li>обмінювати Ігрові цінності на реальні гроші чи інші цінності поза Грою, а також пропонувати подібні послуги;</li>
    <li>ображати, погрожувати, переслідувати інших Гравців і Адміністрацію, розпалювати ворожнечу за будь-якою ознакою;</li>
    <li>поширювати спам, рекламу сторонніх ресурсів, шкідливі посилання;</li>
    <li>видавати себе за представника Адміністрації;</li>
    <li>обманювати інших Гравців з метою заволодіти їхнім Акаунтом чи Ігровими цінностями;</li>
    <li>порушувати інші правила Гри, опубліковані на сайті та форумі.</li>
</ol>

<h2>5. Ігрові цінності та Додаткові послуги</h2>
<ol>
    <li>Усі Ігрові цінності є частиною Гри й належать Адміністрації. Гравець отримує лише право користуватися ними в Грі на час дії Угоди. Ігрові цінності не є майном Гравця й не мають грошової вартості.</li>
    <li>Оплачуючи Додаткові послуги, Гравець набуває права користуватися відповідними ігровими можливостями. Послуга вважається наданою в повному обсязі в момент зарахування Eternum або активації можливості на Акаунті.</li>
    <li>Кошти, сплачені за Додаткові послуги, не повертаються, зокрема в разі блокування Акаунта за порушення Угоди, добровільного припинення гри або зміни ігрового балансу. Виняток — помилкове чи повторне списання, підтверджене Адміністрацією.</li>
    <li>Адміністрація має право змінювати характеристики, вартість і способи отримання Ігрових цінностей, вводити та виводити з Гри предмети й можливості, проводити балансні зміни. Такі зміни не є підставою для компенсації.</li>
    <li>Ігрові цінності, втрачені з вини Гравця (передача пароля, обман з боку інших Гравців, помилкові дії), не відновлюються. Цінності, втрачені через технічний збій на боці Гри, відновлюються на розсуд Адміністрації за наявності підтвердження в журналах сервера.</li>
</ol>

<h2>6. Права Адміністрації</h2>
<ol>
    <li>Адміністрація має право будь-коли змінювати Гру, проводити технічні роботи, тимчасово обмежувати доступ до Гри.</li>
    <li>За порушення Угоди чи правил Гри Адміністрація має право застосувати до Гравця заходи впливу: попередження, обмеження чату, вилучення отриманих нечесним шляхом Ігрових цінностей, тимчасове або безстрокове блокування Акаунта, зокрема всіх пов'язаних Акаунтів.</li>
    <li>Адміністрація не зобов'язана пояснювати Гравцеві причини застосованих заходів, якщо це може допомогти в обході захисту Гри.</li>
    <li>Адміністрація має право видаляти Акаунти, до яких не входили понад 12 місяців і на яких не купувалися Додаткові послуги.</li>
    <li>Адміністрація має право надсилати Гравцеві на вказану адресу електронної пошти службові повідомлення та новини Гри. Від новинних розсилок можна відмовитися.</li>
</ol>

<h2>7. Інтелектуальна власність</h2>
<ol>
    <li>Виключні права на Гру та всі її елементи (код, дизайн, графіка, тексти, назви, ігровий світ) належать Адміністрації або використовуються нею на законних підставах.</li>
    <li>Гравцеві заборонено копіювати, поширювати й використовувати елементи Гри поза Грою з комерційною метою без письмового дозволу Адміністрації. Допускається некомерційне використання скриншотів і відеозаписів ігрового процесу з посиланням на Гру.</li>
</ol>

<h2>8. Обмеження відповідальності</h2>
<ol>
    <li>Адміністрація не несе відповідальності за перебої в роботі Гри, спричинені діями третіх осіб, несправностями обладнання, мереж зв'язку та провайдерів, а також обставинами непереборної сили.</li>
    <li>Адміністрація не відповідає за дії інших Гравців, за зміст їхніх повідомлень, а також за шкоду, що виникла через недотримання Гравцем заходів безпеки під час зберігання пароля.</li>
    <li>У будь-якому разі відповідальність Адміністрації обмежена сумою, сплаченою Гравцем за Додаткові послуги за останні 30 днів.</li>
</ol>

<h2>9. Персональні дані</h2>
<ol>
    <li>Адміністрація обробляє адресу електронної пошти, IP-адресу, дані про входи та ігрові дії Гравця виключно для роботи Гри, захисту від порушень і зв'язку з Гравцем.</li>
    <li>Адміністрація не передає персональні дані третім особам, крім платіжних систем в обсязі, потрібному для оплати, і випадків, передбачених законом.</li>
    <li>Гравець може запросити видалення свого Акаунта й пов'язаних із ним даних, звернувшись до служби підтримки.</li>
</ol>

<h2>10. Зміна та припинення Угоди</h2>
<ol>
    <li>Адміністрація має право змінювати Угоду. Нова редакція набирає чинності з моменту публікації на цій сторінці. Продовження користування Грою означає згоду з новою редакцією.</li>
    <li>Гравець може будь-коли припинити дію Угоди, переставши користуватися Грою або запросивши видалення Акаунта.</li>
    <li>Адміністрація може припинити дію Угоди з Гравцем у разі порушення ним умов Угоди, а також у разі закриття Гри, попередивши про це не менш ніж за 30 днів через новини на сайті.</li>
</ol>

